//! The reference driver of the executor (`asap_run execute`): plan a
//! workload, install the selected plan, ingest every refresh window in time
//! order (the executor's `execute_ingestion`, one ingestion-scope run per
//! window) and evaluate every query root at the requested times (its
//! `execute`, one query-scope run per evaluation time, whose root streams
//! are drained in the request's `RootDrainOrder`).
//!
//! Example: `sum by (job) (sum_over_time(m[1m]))` over four 1 Hz series of
//! constant values 1, 2 (`job="a"`) and 3, 4 (`job="b"`), evaluated at
//! t = 600 s, answers `{job="a"}: 180` and `{job="b"}: 420`: the window
//! `(540 s, 600 s]` holds 60 samples of each series.

use std::collections::BTreeMap;

use asap_accuracy::MeasuredSketchAccuracy;
use asap_cost::CostInputs;
use asap_planner::{
    DeploymentCapabilities, InstallablePlan, MaterializedViewRefresh, PhysicalASAPNodeId,
    PlanningWorkload, SelectedPlanReport,
};

use crate::measurement::samples::{GeneratedDataSettings, Sample, SeriesLabels};

/// Where a run's samples come from.
#[derive(Debug, Clone, PartialEq)]
pub enum DataInput {
    /// Generated by `aqpbm-datagen` from each source's `SourceFacts`.
    GeneratedFromFacts(GeneratedDataSettings),
    /// Given, e.g. read from a JSONL file.
    Samples(Vec<Sample>),
}

/// In which order a query evaluation drains its roots' streams.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RootDrainOrder {
    /// Root 0 first, then root 1, and so on.
    WorkloadOrder,
    /// The last root first.
    Reversed,
    /// Every root at once.
    Concurrent,
}

/// One `asap_run execute` run.
#[derive(Debug, Clone)]
pub struct ExecuteRequest<'a> {
    pub workload: &'a PlanningWorkload,
    pub data: DataInput,
    /// Each evaluation time, in ms, ascending; ingestion starts at the
    /// data's first sample.
    pub evaluation_times_ms: Vec<i64>,
    pub deployment_capabilities: DeploymentCapabilities,
    pub cost_inputs: CostInputs,
    pub accuracy: MeasuredSketchAccuracy,
    pub root_drain_order: RootDrainOrder,
}

impl<'a> ExecuteRequest<'a> {
    /// A run of `workload` over `data` at `evaluation_times_ms`, with
    /// raw data retained, the default cost inputs, no measured accuracy
    /// and roots drained in workload order.
    pub fn new(
        workload: &'a PlanningWorkload,
        data: DataInput,
        evaluation_times_ms: Vec<i64>,
    ) -> Self {
        Self {
            workload,
            data,
            evaluation_times_ms,
            deployment_capabilities: DeploymentCapabilities::default(),
            cost_inputs: CostInputs::default(),
            accuracy: MeasuredSketchAccuracy::default(),
            root_drain_order: RootDrainOrder::WorkloadOrder,
        }
    }
}

/// What one run did and answered.
#[derive(Debug, Clone)]
pub struct ExecutionReport {
    /// The plan installed.
    pub plan: InstallablePlan,
    /// Its predicted cost.
    pub predicted: SelectedPlanReport,
    /// One per evaluation time, in request order.
    pub evaluations: Vec<EvaluationAnswers>,
    /// One per materialized view of the plan.
    pub views: Vec<ViewActivity>,
}

/// The answers of one evaluation.
#[derive(Debug, Clone, PartialEq)]
pub struct EvaluationAnswers {
    pub at_ms: i64,
    /// One per query root, in workload order.
    pub per_root: Vec<RootAnswers>,
}

/// One root's answer: a value per output series.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct RootAnswers {
    pub values: BTreeMap<SeriesLabels, f64>,
}

/// What one materialized view did over the run.
#[derive(Debug, Clone, PartialEq)]
pub struct ViewActivity {
    pub node_id: PhysicalASAPNodeId,
    pub refresh: MaterializedViewRefresh,
    /// How many times it was refreshed.
    pub refresh_count: u64,
    /// The states it held after each evaluation, in evaluation order.
    pub states_after_evaluation: Vec<u64>,
    /// The bytes its states held after each evaluation (each kernel's
    /// `memory_bytes()`).
    pub bytes_after_evaluation: Vec<u64>,
}

/// Why a run did not answer.
#[derive(Debug, Clone, PartialEq)]
#[non_exhaustive]
pub enum ExecuteError {
    /// Planning or installation failed.
    Plan(String),
    /// The data: unreadable, or not generable from the facts.
    Data(String),
    /// An evaluation at `at_ms` before the data covers its warm-up (the
    /// longest retention or raw lookback plus the refresh width), which
    /// starts at `first_covered_ms`.
    BeforeWarmUp { at_ms: i64, first_covered_ms: i64 },
    /// The executor failed.
    Executor(String),
}

